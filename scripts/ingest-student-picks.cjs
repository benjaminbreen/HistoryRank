// ─── Matching logic ──────────────────────────────────────────────────────────

function normalize(s) {
  return s
    .toLowerCase()
    .replace(/['']/g, "'")
    .replace(/[""]/g, '"')
    .replace(/[éèêë]/g, 'e')
    .replace(/[àáâã]/g, 'a')
    .replace(/[íîï]/g, 'i')
    .replace(/[óôõö]/g, 'o')
    .replace(/[úûü]/g, 'u')
    .replace(/[ñ]/g, 'n')
    .replace(/[ō]/g, 'o')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Explicit overrides for tricky matches: pick title → exact JSONL title
const FORCE_MATCH = {
  'Shōgun': 'Shōgun',
  'Fall of Civilizations Podcast': 'Fall of Civilizations Podcast',
  'Sid Meier\'s Civilization V': 'Sid Meier\'s Civilization',
  'Hamilton': 'Hamilton',
  'The Odyssey': null,        // force no match — will be created as new
  'The King': 'The King',
  'Kingdom': 'Kingdom',       // Korean Netflix show, IS in JSONL as "Kingdom"
  'Red Dead Redemption': 'Red Dead Redemption',
};

function titlesMatch(existingTitle, pickTitle, matchTitles) {
  // Check force-match overrides first
  if (pickTitle in FORCE_MATCH) {
    const target = FORCE_MATCH[pickTitle];
    if (target === null) return false;  // force no-match
    return existingTitle === target;
  }

  const normExisting = normalize(existingTitle);
  for (const mt of matchTitles) {
    const normMt = normalize(mt);
    // Exact match
    if (normExisting === normMt) return true;
    // Substring match only if shorter string is at least 5 chars
    // and represents >40% of the longer string (avoids "M" matching everything)
    const shorter = normExisting.length < normMt.length ? normExisting : normMt;
    const longer = normExisting.length < normMt.length ? normMt : normExisting;
    if (shorter.length >= 5 && longer.includes(shorter) && shorter.length / longer.length > 0.35) {
      return true;
    }
  }
  return false;
}

